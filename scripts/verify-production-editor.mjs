/** Read-only checks of the published editor entry and access controls. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'dotenv';
const config = JSON.parse(fs.readFileSync(path.join(process.env.APPDATA, 'byqx-blog-desktop/config.json'), 'utf8'));
const base = process.argv[2] || 'https://www.byqx-blog.online';
const home = await fetch(base + '/', { signal: AbortSignal.timeout(20000) });
assert.equal(home.status, 200);
assert.match(home.headers.get('cache-control'), /no-store/);
const envFile = process.argv[3] || '.env.vercel';
const productionEnv = fs.existsSync(envFile) ? parse(fs.readFileSync(envFile)) : {};
const password = process.env.PRODUCTION_ADMIN_PASSWORD || productionEnv.ADMIN_PASSWORD || config.ADMIN_PASSWORD;
const login = await fetch(base + '/api/login', { method: 'POST', headers: { 'content-type': 'application/json', origin: base }, body: JSON.stringify({ password }), signal: AbortSignal.timeout(20000) });
assert.equal(login.ok, true, `production login HTTP ${login.status}, ${await login.clone().text()}`);
const cookie = login.headers.get('set-cookie').split(';')[0];
const editor = await fetch(base + '/edit', { headers: { cookie }, signal: AbortSignal.timeout(20000) });
assert.equal(editor.status, 200);
const html = await editor.text();
assert.match(html, /id="home-create-article"/);
assert.match(html, /href="\/edit" aria-label="文章编辑"/);
assert.doesNotMatch(html, /id="home-publish-status"/);
const bookmark = await fetch(base + '/edit/new', { headers: { cookie }, redirect: 'manual', signal: AbortSignal.timeout(20000) });
assert.equal(bookmark.status, 302);
assert.equal(bookmark.headers.get('location'), '/edit');
const protectedEditor = await fetch(base + '/edit', { redirect: 'manual', signal: AbortSignal.timeout(20000) });
assert.equal(protectedEditor.status, 302);
assert.match(protectedEditor.headers.get('location'), /^\/login\?/);
console.log('PRODUCTION_HOME_EDITOR_ENTRY_EXPLICIT_CREATE_NO_PUBLICATION_GATE_AUTH_OK');
