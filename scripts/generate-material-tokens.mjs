/** Build-time only: Google's HCT dynamic colour engine never enters the client bundle. */
import { Hct, SchemeTonalSpot, MaterialDynamicColors, argbFromHex, hexFromArgb } from '@material/material-color-utilities';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export const materialSeed = '#1A73E8';
export const materialRoles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow',
  'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'outline', 'outlineVariant', 'inverseSurface', 'inverseOnSurface', 'inversePrimary',
  'surfaceTint', 'shadow', 'scrim',
];
const kebab = (value) => value.replace(/[A-Z]/g, (match) => `-${match.toLowerCase()}`);

export function generateMaterialTokens(isDark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(materialSeed)), isDark, 0);
  return Object.fromEntries(materialRoles.map((role) => [role, hexFromArgb(MaterialDynamicColors[role].getArgb(scheme))]));
}

export function materialTokensCss() {
  const heading = '/* Generated by scripts/generate-material-tokens.mjs. Google Material Color Utilities; Tonal Spot, #1A73E8, normal contrast. */\n';
  return heading + [false, true].map((dark) => {
    const selector = dark ? "html[data-ui-style='material3'].dark" : "html[data-ui-style='material3']";
    return `${selector} {\n${Object.entries(generateMaterialTokens(dark)).map(([role, color]) => `  --m3-${kebab(role)}: ${color};\n  --md-sys-color-${kebab(role)}: var(--m3-${kebab(role)});`).join('\n')}\n}\n`;
  }).join('\n');
}

const destination = new URL('../src/styles/material3-tokens.css', import.meta.url);
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const css = materialTokensCss();
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8') !== css) throw new Error('Material tokens are stale. Run pnpm material:tokens.');
    console.log('Material light/dark colour tokens are current.');
  } else {
    await writeFile(destination, css, 'utf8');
    console.log(`Generated ${materialRoles.length} Material colour roles for light and dark mode.`);
  }
}
