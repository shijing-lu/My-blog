/**
 * 动效令牌（L1 令牌层）
 * ---------------------------------------------------------------------------
 * 依据：docs/05-视觉风格与手作动效规范.md §4.1（已按手作节奏调整）
 *
 * ★ 核心取舍：动效分两档，而不是整体放慢
 *
 *   操作动效 Operational（80–200ms）：用户主动高频触发，需要即时反馈。
 *     勾选、点击、输入、开关、拖拽跟手 —— 一天可能上百次。
 *
 *   环境动效 Ambient（320–720ms）：状态跃迁，低频且值得被看见。
 *     页面转场、区块入场、任务完成、复盘提交。
 *
 *   如果把所有动画都放慢到"手作节奏"，上百次点击会累积成明显的迟钝感。
 *   手作的"慢"应该体现在值得被看见的地方，而不是每次点按钮。
 */

import type { Transition } from "motion/react";

/* ==========================================================================
 * 时长
 * ========================================================================== */
export const duration = {
  instant: 0.08, // 微反馈：按下、勾选、图标切换
  fast: 0.18, // 小元素：Tooltip、Badge、行内展开
  base: 0.32, // 环境：卡片、列表项、面板
  slow: 0.48, // 大元素：模态、抽屉、页面区块
  deliberate: 0.72, // 刻意的强调：空状态入场、图表首次绘制
} as const;

/** 任何**阻塞用户下一步操作**的动画都不得超过 400ms（红线 R10） */
export const BLOCKING_MAX_SECONDS = 0.4;

/* ==========================================================================
 * 缓动（Tween 曲线）
 *
 * 选择规则：
 *   元素出现         → decelerate（快进入、慢落位）
 *   元素消失         → accelerate（慢启动、快离开，不拖泥带水）
 *   元素原地变化      → standard
 *   新增成功类反馈    → overshoot（手作的"不精确"感，全站不超过 3 处）
 * ========================================================================== */
export const ease = {
  standard: [0.32, 0.02, 0.24, 1],
  decelerate: [0.16, 0.84, 0.28, 1],
  accelerate: [0.3, 0, 0.8, 0.15],
  overshoot: [0.28, 1.72, 0.52, 1],
} satisfies Record<string, [number, number, number, number]>;

/** 供 CSS 直接使用的字符串形式 */
export const cssEase = {
  standard: "cubic-bezier(0.32, 0.02, 0.24, 1)",
  decelerate: "cubic-bezier(0.16, 0.84, 0.28, 1)",
  accelerate: "cubic-bezier(0.3, 0, 0.8, 0.15)",
  overshoot: "cubic-bezier(0.28, 1.72, 0.52, 1)",
} as const;

/* ==========================================================================
 * 弹簧
 *
 * 物理属性（位置、缩放、旋转）一律用弹簧而非固定时长补间，
 * 理由：可中断、可续接，在拖拽与布局变化中表现自然。
 *
 * 相比通用 UI 的手作调整：刚度降低、阻尼降低 → 更多回弹、更有"放置"的手感。
 * ========================================================================== */
export const spring = {
  /** 通用位移与布局：干净利落，轻微回弹 */
  smooth: { type: "spring", stiffness: 185, damping: 20, mass: 0.9 },
  /** 轻快元素：小图标、开关、标签 */
  snappy: { type: "spring", stiffness: 340, damping: 22, mass: 0.7 },
  /** 大面板：模态、抽屉，沉稳有重量 */
  gentle: { type: "spring", stiffness: 145, damping: 18, mass: 1.1 },
  /** 强调反馈：新增成功、勾选完成、盖印 */
  bouncy: { type: "spring", stiffness: 460, damping: 14, mass: 0.6 },
  /** 拖拽释放归位：跟随手感，不过度弹跳 */
  settle: { type: "spring", stiffness: 300, damping: 34, mass: 0.85 },
  /** 拖拽跟手 */
  follow: { type: "spring", stiffness: 700, damping: 40, mass: 0.5 },
} satisfies Record<string, Transition>;

